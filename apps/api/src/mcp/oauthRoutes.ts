/** Rendered for the two failures in `GET /oauth/authorize` that happen
 * *before* `redirect_uri` is trusted — an unknown/invalid
 * `client_id`, or a `redirect_uri` that doesn't exactly match the client's
 * registration. Both must **not** redirect: redirecting to an unvalidated
 * URI is exactly the open-redirect hole this ordering exists to close. */
function renderErrorPage(message: string): string {
  return htmlPage(
    'Fehler – xitl',
    `<h1>Anfrage kann nicht verarbeitet werden</h1>
<p>${escapeHtml(message)}</p>`,
  );
}

