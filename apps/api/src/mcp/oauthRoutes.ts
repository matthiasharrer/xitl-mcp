// Copied from haushalts-todos (mcp/oauthRoutes.ts), adapted for xitl ADR-0012 /
// ADR-0014. Discovery metadata + Dynamic Client Registration + the
// authorization-code-with-PKCE flow for the MCP OAuth authorization server:
// every client is bound to the approving user. Differences from Haushalt: the
// protected resource is per upstream (`/mcp/<slug>`), so there is a
// path-aware protected-resource document per slug.
// `/oauth/authorize` (consent, GET+POST — deliberately off the `/mcp` prefix,
// see AUTHORIZE_PATH below) and `/mcp/token` (the grant endpoint) are the two
// endpoints that actually move a client from "has a client_id" to "has an
// access token". Note in particular the ordering rule in `GET
// /oauth/authorize` that avoids an open redirect and the stateless-code
// single-use caveat.
//
// Every artefact minted here goes through `lib/mcpOAuth.ts` (the signed-blob
// crypto core); this file is pure HTTP shaping on top of that, plus the
// SDK's own Zod schemas (`@modelcontextprotocol/core`, a direct dependency
// so importing them isn't reaching into an undeclared transitive package)
// to catch a shape mistake here rather than in a client's face. The SDK also
// ships ready-made `buildOAuthProtectedResourceMetadata`/
// `oauthMetadataResponse` helpers, but their protected-resource output omits
// `bearer_methods_supported` (which the app's own consumers — and RFC 9728
// clients generally — expect), so the metadata objects are built by hand
// here and validated against the schemas instead of generated by those
// helpers.
