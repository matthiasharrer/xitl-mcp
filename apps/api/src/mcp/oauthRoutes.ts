// The consent flow's authorization endpoint lives at **`/oauth/authorize`**, NOT
// under `/mcp/*` like the other OAuth endpoints.
//
// It HAS to be off the `/mcp` prefix: the machine-to-machine endpoints (`/mcp`,
// `/mcp/register`, `/mcp/token`, the well-knowns) are exempt from Authelia so a
// client with no session can reach them — but the consent page MUST stay
// *behind* Authelia, because that ForwardAuth login is the only thing proving
// it's Matthias clicking "Erlauben" and not an anonymous stranger. If it lived
// at `/mcp/authorize`, a `/mcp`-prefix exemption would expose it too and the
// whole flow would authenticate nobody. Off the prefix, the ingress exempts
// `/mcp` cleanly and this stays protected by default.
//
// `/oauth/authorize` rather than a bare `/authorize`: purely tidiness — it
// namespaces the OAuth surface instead of squatting a top-level path. A
// compliant client reads `authorization_endpoint` out of the AS metadata (which
// advertises exactly this path) and follows it there. (A brief earlier build
// used `/authorize` after the connector was seen going there — but that was its
// *fallback when discovery failed*, i.e. while the `/.well-known/oauth-*` docs
// were still behind Authelia and unreadable; with those exempted, the connector
// follows the advertised path and the tidier one is free to use.)
const AUTHORIZE_PATH = '/oauth/authorize';

// xitl has several users (ADR-0010), so "behind Authelia" is not enough: the consent page
// must know WHO approves, because that user gets bound to the client and to
// every token issued for it (ADR-0012). `identity` (the same middleware as on
// /api/*) is mounted on this path in mountMcpOAuth: no `Remote-User` -> 401, and
// the handlers below read `c.get('user')`. Fail closed: a handler that finds no
// user answers 401 even if the middleware were ever removed.

// Double-submit CSRF token for the consent POST. `/oauth/authorize`
// is behind Authelia, whose session cookie is the first line of defence
// (a cross-site POST won't carry a SameSite=Lax/Strict cookie), but that's the
// operator's config, not ours — this is the belt to that suspenders, entirely
// within the app. GET sets a random value as a SameSite=Strict cookie AND
// renders it in a hidden field; POST requires the two to match. A forged
// cross-site POST can neither read the cookie nor make the browser send it, so
// it can't produce a matching field.
const CSRF_COOKIE = 'mcp_oauth_csrf';

// The RFC 9728 well-known path for this server's `/mcp` resource, derived
// from the SDK's own path-building logic rather than hardcoded a second
// time — mount.ts's `resourceMetadataUrl` (the 401 challenge's
// `resource_metadata`) is built from the same helper, so the two can't drift
// apart. Only the *path* is used; the placeholder origin below never
// appears in a response. The per-upstream form (`/mcp/<slug>`, ADR-0014) is
// `${PROTECTED_RESOURCE_PATH}/<slug>`; the SDK helper yields exactly that for
// `/mcp/<slug>` (asserted in the e2e TC-10), so the route below uses the same
// prefix.
const PROTECTED_RESOURCE_PATH = new URL(
  getOAuthProtectedResourceMetadataUrl(new URL('http://placeholder.invalid/mcp')),
).pathname;

const WELL_KNOWN_HEADERS = { 'Cache-Control': 'public, max-age=300' };
const NO_STORE_HEADERS = { 'Cache-Control': 'no-store' };

/** RFC 7591 §3.2.2: a redirect_uri must be an absolute, unparseable-proof
 * URL. `https://` for anything real; `http://` is accepted only for
 * localhost/127.0.0.1, the shape a local CLI client registers with while
 * it's doing its own loopback redirect. */
function isAllowedRedirectUri(raw: string): boolean {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    return false;
  }
  if (url.protocol === 'https:') return true;
  return url.protocol === 'http:' && (url.hostname === 'localhost' || url.hostname === '127.0.0.1');
}

/** Minimal HTML-escaping for values interpolated into the consent/error
 * pages below. Everything embedded there — `client_name` from a DCR
 * registration, `redirect_uri`/`state`/`code_challenge`/`scope` off the
 * query string or form body — is attacker-influenced, so this isn't
 * decorative: an unescaped `client_name` or `state` is a stored/reflected
 * XSS in a page that's about to ask the user to click "Erlauben". */
function escapeHtml(input: string): string {
  return input
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

